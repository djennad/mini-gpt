def capital_turn(rng):
    country = rng.choice(list(CAPITALS))
    q = rng.choice(["ما عاصمة {c}؟", "ما هي عاصمة {c}؟", "هل تعرف عاصمة {c}؟", "عاصمة {c}؟",
                    "أخبرني ما هي عاصمة {c}", "ما اسم عاصمة {c}؟"])
    a = rng.choice(["عاصمة {c} هي {k}.", "{k} هي عاصمة {c}."])
    return country, q.format(c=country), a.format(c=country, k=CAPITALS[country])


def capital_conversation(rng):
    """A capital question, optionally followed by 'and what about X?' that relies on context."""
    country, q, a = capital_turn(rng)
    messages = [("user", q), ("assistant", a)]
    for _ in range(rng.choice([0, 0, 1, 2])):
        other = rng.choice([c for c in CAPITALS if c != country])
        follow = rng.choice(["وماذا عن {c}؟", "و{c}؟", "وعاصمة {c}؟"]).format(c=other)
        messages += [("user", follow), ("assistant", f"عاصمة {other} هي {CAPITALS[other]}.")]
        country = other
    return messages


